def initialize(data, task, source, protocol, out):
    out = Path(out)
    if task['split'] != 'training' or out.exists():
        raise ValueError('New training-only attempts required')
    out.mkdir(parents=True)
    before = prepare(Path(data)/'snapshots'/task['repository'].replace('/', '--'), out/'workspace', source, task)
    state = {'schema_version': 1, 'id': task['id'], 'repository': task['repository'], 'family': task['family'],
             'split': 'training', 'branch': 'prefix', 'producer_kind': 'model',
             'protocol_sha256': digest(json.dumps(protocol, sort_keys=True).encode()),
             'started_epoch': time.time(), 'complete': False, 'boundary': 'before_generation',
             'messages': initial_messages(task, protocol), 'steps': [], 'backend_identities': {},
             'attempted_calls': 0, 'generated_tokens': 0, 'actor_seconds': 0., 'submitted': False,
             'terminal_reason': None, 'verified_source': None,
             'original_source_sha256': {n: before[n] for n in task['editable_files']}}
    write_json(out/'before.json', before)
    atomic(out/'trajectory.json', state)
    return state


def identity_ok(health, protocol, role):
    return (health['model_id'] == protocol['model_id'] and health['revision'] == protocol['revision']
            and health['profile_sha256'] == protocol['evaluation_profile_sha256']
            and health['adapter'] is (role == 'student')
            and health.get('adapter_sha256', {}) == (protocol['adapter_sha256'] if role == 'student' else {}))


def advance(root, task, protocol, out, state, backend, runner, role, stop_after_calls=12):
    """Continue only from a known feedback boundary, with cumulative path costs."""
    out = Path(out); budget = protocol['evaluation_budget']; policy = protocol['agent_policy']
    if (state['complete'] or state.get('unknown_inflight_generation_cost')
            or state['boundary'] not in {'before_generation', 'completed_step'}):
        raise ValueError('Do not resume unknown or terminal actor state')
    if role not in {'student', 'base'} or (state['attempted_calls'] < 3 and role != 'student'):
        raise ValueError('Prefix must be generated by the original student')
    if state['terminal_reason']:
        return state
    health = request(backend, {'operation': 'health'})
    if not identity_ok(health, protocol, role):
        raise ValueError('Unexpected continuation artifact')
    state['backend_identities'][role] = health
    norm = normalization(root)
    workspace = out/'workspace'; key = str(workspace.resolve())
    guard = SubmissionGuard(runner, {key: {k: task[k] for k in ['editable_files', 'regression_command']}})
    if state.get('verified_source') is not None:
        if state['verified_source'] != guard.source_state(workspace, task):
            raise ValueError('Saved verification is stale')
        guard.verified[key] = copy.deepcopy(state['verified_source'])
    consumed = state['actor_seconds']; started = time.monotonic()
    def save():
        state['actor_seconds'] = consumed + time.monotonic() - started
        atomic(out/'trajectory.json', state)
    for call in range(state['attempted_calls']+1, min(stop_after_calls, budget['max_model_calls'])+1):
        state['actor_seconds'] = consumed + time.monotonic() - started
        remaining = remaining_budget(budget, state)
        if remaining['actor_seconds'] <= 0 or remaining['generated_tokens'] <= 0:
            state['terminal_reason'] = 'time_limit' if remaining['actor_seconds'] <= 0 else 'token_limit'
            break
        payload = {'operation': 'generate', 'messages': copy.deepcopy(state['messages']), 'agent_policy': policy,
                   'max_input_tokens': budget['max_input_tokens'], 'max_new_tokens': remaining['next_generation_cap']}
        request_path = out/f'request-{call:03d}.json'
        if request_path.exists():
            raise ValueError('No duplicate generation request')
        write_json(request_path, payload)
        state.update(boundary='in_flight', attempted_calls=call); save()
        try:
            generated = request(backend, payload, timeout=max(1, min(180, remaining['actor_seconds'])))
        except Exception as error:
            state.update(terminal_reason='backend_error', backend_error_type=type(error).__name__,
                         unknown_inflight_generation_cost=True)
            save()
            raise RuntimeError('Stop pilot after unaccounted generation; no retry') from None
        state['generated_tokens'] += generated['generated_tokens']
        step = {'call': call, 'model_role': role, 'request_sha256': digest(request_path.read_bytes()),
                'generation': generated, 'source_before': guard.source_state(workspace, task), 'action_format_valid': False}
        assistant = {'role': 'assistant', 'content': generated['text'], 'extra': {}}
        state['messages'].append(assistant)
        try:
            action = parse_action(generated['text'])
        except ValueError:
            state['messages'].append({'role': 'user', 'content': format_feedback(policy)})
            state['steps'].append(step); state['boundary'] = 'completed_step'; save(); continue
        step.update(action_format_valid=True, command=action['command']); assistant['extra']['actions'] = [action]
        seconds = budget['max_task_seconds'] - (consumed + time.monotonic() - started)
        if seconds <= 0:
            state['steps'].append(step); state['terminal_reason'] = 'time_limit_before_tool'; break
        guard.timeout = max(1, min(budget['max_tool_seconds'], int(seconds)))
        output = guard.execute(workspace, action['command'])
        write_json(out/f'tool-{call:03d}.json', output)
        raw = output['output']; cap = budget['max_tool_output_chars']
        delivered, receipt = norm.transform(raw if len(raw) <= cap else raw[:cap]+norm.MARKER, 'extended', cap)
        step.update(observation={k: v for k, v in output.items() if k != 'output'}, normalization=receipt)
        try:
            after = files(workspace); step['source_after'] = {n: after.get(n) for n in task['editable_files']}
        except ValueError:
            state['steps'].append(step); state['terminal_reason'] = 'unsafe_workspace'; break
        state['messages'].append({'role': 'user', 'content': f"Exit code: {output['returncode']}\n{delivered}",
                                  'extra': {'tool': step['observation']}})
        state['verified_source'] = copy.deepcopy(guard.verified.get(key))
        state['steps'].append(step); state['boundary'] = 'completed_step'; save()
        if action['command'] == SUBMIT and output['returncode'] == 0:
            state.update(submitted=True, terminal_reason='submitted'); break
    if state['terminal_reason'] is None and state['attempted_calls'] >= budget['max_model_calls']:
        state['terminal_reason'] = 'call_limit'
    save()
    return state


def capture_prefix(out, state, destination):
    validate_prefix(state)
    return capture(Path(out)/'workspace', destination, state)


def fork_prefix(prefix_out, snapshot, receipt, out, branch):
    out, prefix_out = Path(out), Path(prefix_out)
    if branch not in {'student', 'teacher'} or out.exists():
        raise ValueError('Fresh registered continuation required')
    out.mkdir(parents=True)
    state = restore(snapshot, out/'workspace', receipt)
    write_json(out/'restored-state.json', {'manifest_sha256': digest(canonical(inventory(out/'workspace'))),
        'prefix_sha256': receipt['prefix_sha256'], 'actor_seconds': state['actor_seconds'],
        'attempted_calls': state['attempted_calls'], 'generated_tokens': state['generated_tokens']})
    state.update(branch=branch, shared_prefix_receipt=receipt, shared_prefix_calls=state['attempted_calls'],
                 shared_prefix_generated_tokens=state['generated_tokens'], shared_prefix_actor_seconds=state['actor_seconds'])
    for path in [prefix_out/'before.json', *prefix_out.glob('request-*.json'), *prefix_out.glob('tool-*.json')]:
        shutil.copyfile(path, out/path.name)
    atomic(out/'trajectory.json', state)
    return state


def finish(data, task, source, protocol, out, state, runner):
    out = Path(out); budget = protocol['evaluation_budget']
    if state['complete'] or not state['terminal_reason'] or state.get('unknown_inflight_generation_cost'):
        raise ValueError('Only a fully accounted terminal actor may be graded')
    before = json.loads((out/'before.json').read_text())
    def execute(workspace, command):
        runner.timeout = budget['max_tool_seconds']; output = runner.execute(workspace, command)
        write_json(out/'grader-output.json', output); return output
    grading_started = time.monotonic()
    try:
        result = grade(Path(data)/'snapshots'/task['repository'].replace('/', '--'), out/'grader',
                       source, task, out/'workspace', before, execute)
    except ValueError:
        # Record only genuinely unsafe actor state as an ordinary task failure.
        try: files(out/'workspace')
        except ValueError: result = {'passed': False, 'reason': 'unsafe_workspace'}
        else: raise
    final = SubmissionGuard.source_state(out/'workspace', task)
    compliant = (state['actor_seconds'] <= budget['max_task_seconds']
                 and state['attempted_calls'] <= budget['max_model_calls']
                 and state['generated_tokens'] <= budget['max_total_generated_tokens']
                 and len(state['steps']) == state['attempted_calls']
                 and all(s['generation']['generated_tokens'] <= budget['max_generated_tokens_per_call']
                         and s['generation']['input_tokens'] <= budget['max_input_tokens'] for s in state['steps']))
    verified = state.get('verified_source') is not None and state['verified_source'] == final
    state.update(complete=True, boundary='finished', grade=result, finished_epoch=time.time(),
                 grader_seconds=time.monotonic()-grading_started, final_source_sha256=final,
                 actor_budget_compliant=compliant, success_within_budget=result['passed'] and compliant,
                 agent_verified_final_source=verified)
    state['eligible_verified_trajectory'] = bool(state['success_within_budget'] and state['submitted'] and verified)
    atomic(out/'trajectory.json', state)
    value = {k: state[k] for k in ['id', 'repository', 'family', 'split', 'branch', 'complete', 'generated_tokens',
              'attempted_calls', 'actor_seconds', 'grader_seconds', 'submitted', 'terminal_reason',
              'actor_budget_compliant', 'success_within_budget', 'agent_verified_final_source', 'eligible_verified_trajectory']}
    value.update(grader_passed=result['passed'], grade_reason=result['reason'],
                 trajectory_sha256=digest((out/'trajectory.json').read_bytes()),
                 first_edit_call=next((s['call'] for s in state['steps'] if s.get('source_after') and s['source_after'] != s['source_before']), None),
                 input_tokens=sum(s['generation']['input_tokens'] for s in state['steps']),
                 invalid_actions=sum(not s['action_format_valid'] for s in state['steps']))
    write_json(out/'result.json', value)
    return value
